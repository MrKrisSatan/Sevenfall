-- Native doctrine effects and counterplay, using real attacks and power changes.
local checks, failures = 0, 0
local choir, area, circle, enemy, actors, throne = nil,nil,nil,nil,{},nil
local function A(name) return actors[name] end
local function Check(ok,name)
 if ok then checks=checks+1;print('DOCTRINE_TEST PASS: '..name)
 else failures=failures+1;print('DOCTRINE_TEST FAIL: '..name) end
end
local function Later(t,fn) Trigger.AfterDelay(DateTime.Seconds(t),fn) end
local longHealth, nearHealth, offHealth
WorldLoaded=function()
 choir=Player.GetPlayer('Choir');area=Player.GetPlayer('Area');circle=Player.GetPlayer('Circle');enemy=Player.GetPlayer('Enemy')
 for _,name in ipairs({'ChoirPower','AreaPower','CirclePower','EnemyPower','Cantor','SelfMartyr','Martyr1','Martyr2','Martyr3','Martyr4','Protected','Dread','Executor','Pylon','Janus','LongTarget','NearTarget','NullAngel','Retrieval','Magistrate','Beast','MarkedTarget','SecondTarget','Shrine','ShrineFollower','WireWalker'}) do actors[name]=Map.NamedActor(name) end
 Camera.Position=Map.CenterOfCell(CPos.New(30,25))
 A('NullAngel').Health=7000
 A('WireWalker').Move(CPos.New(35,29))
 Later(1,function()
  Check(A('Protected').ConvictionProtected,'Cantor grants Conviction')
  Check(A('ShrineFollower').ConvictionProtected,'powered shrine extends hymn network')
  Check(A('NullAngel').NullSuppressed,'containment field affects friendly supernatural units')
  Check(not area.AbyssProtocol,'SERAPH is default protocol')
  Check(A('WireWalker').NullSuppressed,'wire crossing is inside the null field')
  A('SelfMartyr').Kill()
  A('Magistrate').Attack(A('MarkedTarget'))
  longHealth=A('LongTarget').Health;A('Janus').Attack(A('LongTarget'),false)
 end)
 Later(2,function()Check(not A('WireWalker').IsDead and A('WireWalker').Health<A('WireWalker').MaxHealth,'physical razorwire remains harmful inside a null field');Check(choir.Resonance==0,'self-inflicted martyrdom grants no Resonance');A('Executor').Stop();A('Executor').Attack(A('Martyr1')) end)
 Later(3,function()
  Check(circle.CondemnedTarget==A('MarkedTarget'),'Magistrate attack condemns its target')
  Check(A('MarkedTarget').DoctrineDamageFrom(A('Beast'))==115,'Circle-only condemnation grants 15 percent damage')
  Check(A('MarkedTarget').DoctrineDamageFrom(A('Retrieval'))==100,'foreign factions gain no condemnation damage')
  A('Magistrate').Stop()
 end)
 Later(4,function()
  Check(choir.Resonance==1,'enemy kill grants one Last Hymn stack')
  Check(A('LongTarget').Health<longHealth,'SERAPH Janus hits a long-range target')
  A('Executor').Stop();A('Executor').Attack(A('Martyr2'));A('Pylon').ToggleProtocol()
 end)
 Later(5,function()
  Check(not area.AbyssProtocol,'protocol cannot switch instantly')
  throne=Actor.Create('d_throne',true,{Owner=circle,Location=CPos.New(60,13)})
 end)
 Later(6,function()Check(choir.Resonance==2,'second martyr adds a stack');A('Executor').Stop();A('Executor').Attack(A('Martyr3')) end)
 Later(7,function()
  Check(A('MarkedTarget').DoctrineDamageFrom(A('Beast'))==130,'Throne strengthens a nearby living Magistrate')
  A('MarkedTarget').Health=400000
  Check(A('MarkedTarget').DoctrineDamageFrom(A('Beast'))==169,'Contemptor executes damaged targets with bounded combined bonus')
 end)
 Later(8,function()
  Check(choir.Resonance==3,'third martyr reaches cap');A('Executor').Stop();A('Executor').Attack(A('Martyr4'))
  Check(area.AbyssProtocol,'ABYSS activates after transition')
  A('Janus').Stop();nearHealth=A('NearTarget').Health;A('Janus').Attack(A('NearTarget'),false)
  A('MarkedTarget').Health=100;A('Beast').Attack(A('MarkedTarget'))
 end)
 Later(10,function()Check(choir.Resonance==3,'further martyrs cannot exceed three stacks');Check(A('Cantor').DoctrineFirepower==145,'Last Hymn actually strengthens nearby angel attacks') end)
 Later(12,function()
  Check(circle.Ascendancy,'destroying a condemned target grants Ascendancy')
  Check(circle.CondemnedTarget==nil,'destroyed target clears condemnation')
  Check(A('NearTarget').Health<nearHealth,'ABYSS Janus fires its infernal weapon')
  Check(A('NullAngel').Health==7000,'null field pauses angelic Renewal')
  A('Pylon').ToggleProtocol()
 end)
 Later(16,function()
  Check(not area.AbyssProtocol,'protocol can return to SERAPH')
  Check(A('Protected').Owner==choir,'Conviction prevents flesh-wall conversion')
  Check(not circle.Ascendancy,'Ascendancy expires')
  Check(choir.Resonance==0,'Last Hymn expires without more martyrdom')
  Check(A('Cantor').DoctrineFirepower==100,'expired Last Hymn restores normal firepower')
  A('AreaPower').Kill()
 end)
 Later(18,function()
  offHealth=A('NearTarget').Health
  A('Janus').Stop();A('Janus').Attack(A('NearTarget'),false)
  Check(not A('NullAngel').NullSuppressed,'power loss disables containment field')
  A('Magistrate').Attack(A('SecondTarget'))
 end)
 Later(20,function()
  Check(circle.CondemnedTarget==A('SecondTarget'),'retarget cooldown eventually permits another condemnation')
  A('Magistrate').Kill()
 end)
 Later(22,function()
  Check(circle.CondemnedTarget==nil,'killing Magistrate cancels condemnation')
  Check(A('NearTarget').Health==offHealth,'Janus cannot fire without powered containment')
 end)
 Later(32,function()
  Check(A('NullAngel').Health>7000,'Renewal resumes after containment power loss')
  if failures==0 then print('DOCTRINE_TEST COMPLETE checks='..checks) end
 end)
end

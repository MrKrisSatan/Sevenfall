-- Real native conditions, damage and ordinary support-power manager orders.
local checks,failures=0,0
local players,units,enemies,armor,buildings={},{},{},{},{}
local broodVictim
local function A(n) return Map.NamedActor(n) end
local function Check(ok,name)
 if ok then checks=checks+1;print('IDENTITY_TEST PASS: '..name)
 else failures=failures+1;print('IDENTITY_TEST CHECK_FAILED: '..name) end
end
local function Later(t,fn) Trigger.AfterDelay(DateTime.Seconds(t),fn) end
WorldLoaded=function()
 broodVictim=A('BroodVictim')
 Camera.Position=Map.CenterOfCell(CPos.New(44,36))
 for i=1,12 do
  players[i]=Player.GetPlayer('F'..i);units[i]=A('Unit'..i);enemies[i]=A('Enemy'..i);armor[i]=A('Armor'..i);buildings[i]=A('Building'..i)
 end
 units[3].Health=12000;units[6].Health=15000;units[7].Health=18000;units[10].Health=18000
 enemies[12].Health=12000
 A('BroodKiller').Health=19000
 Later(1,function()
  A('BroodKiller').IdentityDamage(A('BroodVictim'),100000)
  A('CourtCaster').Attack(A('CourtVictim'))
 end)
 Later(3,function()
  Check(broodVictim.IsDead and A('BroodKiller').Health>19000,'Brood enemy kill feeds and heals killer')
  Check(A('BroodKiller').ActiveIdentity=='sf-fed','Brood feeding grants timed identity')
  print('IDENTITY_DEBUG court speed='..A('CourtVictim').IdentitySpeed..' fire='..A('CourtVictim').DoctrineFirepower)
  Check(A('CourtVictim').IdentitySpeed<=65 and A('CourtVictim').DoctrineFirepower==75,'Court attack applies real slow and weakness')
  A('CourtCaster').Stop()
 end)
 Later(6,function()
  Check(units[1].ActiveIdentity=='sf-focus' and units[1].DoctrineFirepower==130,'Synod prepares a real charged volley')
  Check(units[2].ActiveIdentity=='sf-aegis' and units[2].IdentityArmor==75,'Gate formation protects nearby ally')
  Check(units[3].ActiveIdentity=='sf-defiance' and units[3].DoctrineFirepower==135,'Unshackled wounded state increases firepower')
  Check(units[5].ActiveIdentity=='sf-entrenched' and units[5].IdentityArmor==80,'Bastion entrenchment reduces actual damage')
  Check(units[6].ActiveIdentity=='sf-logistics' and units[6].IdentitySpeed==115,'Union supply corridor increases movement')
  Check(units[7].ActiveIdentity=='sf-oath' and units[7].Health>18000,'Covenant aura heals wounded infantry')
  Check(units[9].ActiveIdentity=='sf-iron' and units[9].IdentityArmor==75,'Legion formation reduces incoming damage')
  for i=1,12 do
   Check(not A('Specialist'..i).IsDead,'exclusive specialist loads animated body '..i)
   Check(players[i].FactionPowerReady,'faction superweapon charges '..i)
   Check(players[i].FireFactionPower(units[i].Location),'normal power order consumes ready charge '..i)
  end
  units[1].Move(units[1].Location+CVec.New(-3,0))
  units[5].Move(units[5].Location+CVec.New(-3,0))
 end)
 Later(7,function()
  Check(units[1].ActiveIdentity=='none','movement interrupts Synod focus')
  Check(units[5].ActiveIdentity=='none','movement breaks Bastion entrenchment')
  Check(not A('Power1').IsDead and enemies[1].Health==30000,'superweapon warning allows a response before impact')
 end)
 Later(11,function()
  Check(enemies[1].Health==15000,'Dawn damages enemy troops')
  Check(units[2].IdentityArmor==26,'Unbroken Gate protection multiplies with formation armor')
  Check(units[3].IdentitySpeed>=150 and units[3].DoctrineFirepower>=140,'Rebellion trades exposure for speed and firepower')
  Check(units[4].DoctrineFirepower==145 and enemies[4].DoctrineFirepower==75,'Requiem empowers allies and weakens enemy infantry')
  Check(enemies[5].Health<30000,'Rolling Thunder performs advancing impacts')
  Check(units[6].Health>=24000 and units[6].IdentitySpeed>=130,'Emergency Airlift repairs and accelerates troops')
  Check(units[7].Health==30000 and units[7].IdentityArmor==18,'Ashes to Ashes restores infantry and protects them')
  Check(enemies[8].Health==18000 and enemies[8].IdentitySpeed==0,'Event Horizon damages and locks enemies')
  Check(units[8].IdentitySpeed==0 and units[8].NullSuppressed,'Event Horizon also locks and suppresses friendly troops')
  Check(buildings[9].IsDead and armor[9].Health<300000,'Ninth Furnace destroys enemy infrastructure and damages armor')
  Check(units[10].Health>25500,'Red Deluge heals and regenerates allied infantry')
  Check(enemies[11].DoctrineFirepower==0 and enemies[11].IdentitySpeed==0,'Nameless Silence disables enemy movement and weapon damage')
  Check(enemies[12].IsDead and armor[12].Health==292000,'Final Verdict punishes wounded targets more than healthy armor')
  Check(units[12].DoctrineFirepower==145,'Final Verdict empowers nearby allies')
  Check(A('BroodKiller').ActiveIdentity=='none','ordinary feeding expires without another kill')
  Check(A('CourtVictim').DoctrineFirepower==100,'ordinary Court curse expires')
 end)
 Later(12,function() A('BroodKiller').IdentityDamage(A('BroodFriendly'),100000) end)
 Later(13,function() Check(A('BroodKiller').ActiveIdentity=='none','friendly kills grant no Brood feeding') end)
 Later(14,function()
  Check(players[1].FireFactionPower(armor[1].Location),'second power can be ordered after recharge')
  Check(players[9].FireFactionPower(armor[9].Location),'siege power recharges through normal manager')
  Check(players[3].FireFactionPower(units[3].Location),'army buff recharges through normal manager')
 end)
 Later(15,function() A('Ultimate1').Kill();A('Power9').Kill();A('Reserve9').Kill();A('Ultimate3').Owner=Player.GetPlayer('Enemy') end)
 Later(19,function()
  Check(armor[9].Health==290000,'losing power cancels warned siege strike')
  Check(armor[1].Health==285000,'destroying installation cancels warned strike')
  Check(enemies[8].IdentitySpeed==100 and enemies[8].NullSuppressed,'lock expires while longer null suppression remains')
  A('Gate').Move(CPos.New(32,19))
  A('Supply').Move(CPos.New(60,41))
  A('Iron').Move(CPos.New(60,62))
  A('Specialist2').Move(CPos.New(32,18))
  A('Specialist6').Move(CPos.New(60,40))
  A('Specialist9').Move(CPos.New(60,61))
 end)
 Later(31,function() Check(units[3].DoctrineFirepower==135,'capturing installation cancels old owner army buff') end)
 Later(42,function()
  Check(units[2].ActiveIdentity=='none','formation benefit expires outside Gate range')
  Check(units[6].ActiveIdentity=='none','mobile supply benefit expires outside corridor')
  Check(units[9].ActiveIdentity=='none','Legion benefit expires outside command formation')
  Check(not enemies[8].NullSuppressed,'Event Horizon suppression expires after thirty seconds')
  Check(enemies[11].IdentitySpeed==100 and enemies[11].DoctrineFirepower==100,'Silence expires without permanent disable')
  if failures==0 then print('IDENTITY_TEST COMPLETE checks='..checks) else print('IDENTITY_TEST FAIL: '..failures..' failed, '..checks..' passed') end
 end)
end
Tick=function() end

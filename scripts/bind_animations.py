"""Bind validated authored animation exports to the implemented OpenRA roster.

Run after prepare_animations.cjs. --available binds only complete asset groups
for local iteration; the normal command requires all 63 unit/building designs.
"""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
MOD = ROOT / 'mods/sevenfall'
FACTIONS = {
    'a': ('a_seraph', 'a_warden', 'a_exile', 'a_desolation'),
    'h': ('h_bastion', 'h_union', 'h_covenant', 'h_area52'),
    'd': ('d_legion', 'd_brood', 'd_court', 'd_contempt'),
}


def animated_sequence(name, unit, start, length=4, stride=None, scale=None):
    result = f'\t{name}:\n\t\tFilename: sevenfall|art/animations/{unit}.png\n\t\tStart: {start}\n\t\tLength: {length}\n\t\tFacings: -8\n\t\tTick: 100\n'
    if stride:
        result += f'\t\tStride: {stride}\n'
    if scale is not None:
        result += f'\t\tScale: {scale}\n'
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--available', action='store_true')
    args = parser.parse_args()
    assets = json.loads((ROOT / 'art/animations/manifest.json').read_text(encoding='utf-8'))['assets']
    if not args.available and (sum(a['kind'] == 'unit' for a in assets) != 24
                               or sum(a['kind'] == 'building' for a in assets) != 39):
        parser.error('Expected complete exports for 24 units and 39 buildings')
    source = (MOD / 'rules/30-units.yaml').read_text(encoding='utf-8')
    sequences = '# Generated by scripts/bind_animations.py from authored pose/damage exports.\n'
    rules = '# Generated animation bindings. Gameplay weapons and prerequisites remain in 30-units.yaml.\n'
    rules += '''^SF_ANIMATED_DEATH:
	Inherits: ^BasicHusk
	Inherits@SF_SPRITES: ^SpriteActor
	Husk:
		AllowedTerrain: Clear, Rough, Road, Ore, Gems, Beach, Water, River
	QuantizeFacingsFromSequence:
		Sequence: corpse
	WithFacingSpriteBody:
		StartSequence: die
		Sequence: corpse
	KillsSelf:
		Delay: 150
		RemoveInstead: True
	-MapEditorData:
'''
    mcvs = []
    for asset in assets:
        ident = asset['id']
        if asset['kind'] != 'unit':
            continue
        actor = ident.replace('-', '_')
        is_mcv = ident.endswith('-mcv')
        is_miner = ident.endswith(('-gatherer', '-harvester', '-devourer'))
        image = ident[0] + '_harvester' if is_miner else actor
        match = re.search(rf'(?ms)^{actor.upper()}:\n(.*?)(?=^[A-Z][A-Z0-9_]+:|\Z)', source)
        infantry = bool(match and re.search(r'^\tInherits: E[123]$', match[1], re.M))
        # Exported frames are already normalized to the intended game drawSize.
        scale = 1
        sequences += f'{image}:\n'
        for sequence in ('run', 'move'):
            sequences += animated_sequence(sequence, ident, 0, scale=scale)
        for sequence in ('shoot', 'throw', 'harvest', 'dock', 'dock-loop'):
            sequences += animated_sequence(sequence, ident, 32, scale=scale)
        sequences += animated_sequence('die', ident, 64, scale=scale)
        sequences += animated_sequence('corpse', ident, 67, length=1, stride=4, scale=scale)
        if infantry:
            # No prone poses have been authored in this pass. Keep the real walk/
            # attack cycles when TakeCover is active, instead of a static fallback.
            for sequence, start in [('prone-run', 0), ('prone-shoot', 32), ('prone-throw', 32)]:
                sequences += animated_sequence(sequence, ident, start, scale=scale)
        if asset['frames'] == 192:
            for sequence in ('idle', 'stand', 'stand2', 'idle1', 'idle2', 'parachute'):
                sequences += animated_sequence('damaged-' + sequence, ident, 96, length=1, stride=4, scale=scale)
            for sequence in ('run', 'move', 'prone-run'):
                sequences += animated_sequence('damaged-' + sequence, ident, 96, scale=scale)
            for sequence in ('shoot', 'throw', 'prone-shoot', 'prone-throw', 'harvest', 'dock', 'dock-loop'):
                sequences += animated_sequence('damaged-' + sequence, ident, 128, scale=scale)
        sequences += '\n'
        # Death actors use a separate image namespace so a fresh, full-health
        # husk cannot normalize a damaged death sequence back to healthy art.
        sequences += f'{image}_death:\n'
        death_start = 160 if asset['frames'] == 192 else 64
        sequences += animated_sequence('die', ident, death_start, scale=scale)
        sequences += animated_sequence('corpse', ident, death_start + 3, length=1, stride=4, scale=scale)
        sequences += '\n'
        if is_mcv:
            mcvs.append(image + '_death')
            continue
        rules += f'{actor.upper()}:\n\tSpawnActorOnDeath@SF_ANIMATION:\n\t\tActor: {actor}.death\n'
        if not infantry:
            rules += '\tWithMoveAnimation:\n\t\tMoveSequence: move\n'
            if is_miner:
                rules += '\t-SpawnActorOnDeath:\n\t-HarvesterHuskModifier:\n'
            else:
                if actor == 'h_siegegun':
                    # The launcher has two inherited bodies. Keep one body so
                    # move/attack animation traits can resolve it unambiguously.
                    rules += '\t-WithFacingSpriteBody@EMPTY:\n\tWithFacingSpriteBody:\n\t\t-RequiresCondition:\n\t\tName: body\n'
                    rules += '\tArmament:\n\t\t-ReloadingCondition:\n'
                rules += '\tWithAttackAnimation:\n\t\tSequence: shoot\n\t\tDelayRelativeTo: Attack\n'
        rules += f'{actor.upper()}.DEATH:\n\tInherits: ^SF_ANIMATED_DEATH\n\tRenderSprites:\n\t\tImage: {image}_death\n\n'
    if mcvs:
        if len(mcvs) != 3:
            if not args.available:
                parser.error('All three MCV animation exports are required')
        else:
            rules += 'MCV:\n\t-SpawnActorOnDeath:\n\tWithMoveAnimation:\n\t\tMoveSequence: move\n\tSpawnActorOnDeath@SF_ANIMATION:\n\t\tActor: mcv.sfdeath\n'
            rules += 'MCV.SFDEATH:\n\tInherits: ^SF_ANIMATED_DEATH\n\tRenderSprites:\n\t\tImage: h_mcv_death\n\t\tFactionImages:\n'
            for side, factions in FACTIONS.items():
                for faction in factions:
                    rules += f'\t\t\t{faction}: {side}_mcv_death\n'
    # Existing offsets and terrain palettes remain inherited from base sequences.
    for asset in assets:
        if asset['kind'] != 'building':
            continue
        ident = asset['id']
        image = ident.replace('-', '_')
        sequences += f'{image}:\n'
        for prefix, frame in [('damaged-', 0), ('critical-', 1)]:
            for state in ('idle', 'active', 'build'):
                sequences += f'\t{prefix}{state}:\n\t\tFilename: sevenfall|art/animations/{ident}-damage.png\n\t\tStart: {frame}\n\t\tLength: 1\n'
                if ident.endswith('-veilworks') and state == 'idle':
                    sequences += '\t\tZOffset: -1c511\n'
        sequences += f'\tdead:\n\t\tFilename: sevenfall|art/animations/{ident}-damage.png\n\t\tStart: 2\n\t\tLength: 1\n\n'
    (MOD / 'rules/35-animations.yaml').write_text(rules, encoding='utf-8')
    (MOD / 'sequences/animations.yaml').write_text(sequences, encoding='utf-8')
    print(f'Bound {len(assets)} authored animation/damage exports')


if __name__ == '__main__':
    main()

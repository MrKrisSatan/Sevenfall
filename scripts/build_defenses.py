"""Generate the first faction defense roster, weapons and localization from its design catalogue."""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[1]
MOD = ROOT / 'mods/sevenfall'


def main():
    catalogue = json.loads((ROOT / 'art/defenses/catalogue.json').read_text(encoding='utf-8'))
    rules = '''# Generated by scripts/build_defenses.py. Original Sevenfall defense roster.
^SF_EMPLACEMENT:
	Inherits: ^Defense
	Inherits@SF_SHAPE: ^2x2Shape
	Building:
		Dimensions: 2,2
		Footprint: xx xx
	Selectable:
		Bounds: 2048, 2048
	-SpawnActorsOnSell:
	WithSpriteBody:
	WithTextDecoration@OWNER:
		Text: ===
		UsePlayerColor: True
		Position: BottomRight
		ValidRelationships: Ally, Neutral, Enemy
		RequiresSelection: False
	RevealsShroud:
		Range: 6c0
	Armor:
		Type: Heavy

^SF_WALL:
	Inherits: ^Wall
	-WithWallSpriteBody:
	WithSpriteBody:
	RevealsShroud:
		Range: 2c0
		Type: CenterPosition
	Armor:
		Type: Wood

'''
    sequences = '# Generated from original six-state defense atlases.\n'
    messages = []
    weapons = '''# Sevenfall defense tuning. Existing engine effects remain prototype scaffolding.
SF_Watchfire:
	Inherits: SF_HaloLance
	ReloadDelay: 24
	Range: 5c512
	Warhead@1Dam:
		Damage: 3000
		ValidRelationships: Enemy
		Versus:
			None: 150
			Light: 45
			Heavy: 12
			Wood: 30
			Concrete: 15
SF_Judgment:
	Inherits: SF_HaloLance
	ReloadDelay: 100
	Range: 7c0
	Warhead@1Dam:
		Damage: 12000
		ValidRelationships: Enemy
		Versus:
			None: 15
			Light: 110
			Heavy: 125
			Wood: 55
			Concrete: 50
SF_Autocannon:
	Inherits: SF_PulseRifle
	ReloadDelay: 24
	Range: 6c0
	Warhead@1Dam:
		Damage: 4000
		ValidRelationships: Enemy
		Versus:
			None: 85
			Light: 100
			Heavy: 60
			Wood: 35
			Concrete: 25
SF_Spines:
	Inherits: SF_PulseRifle
	ReloadDelay: 25
	Range: 5c0
	Warhead@1Dam:
		Damage: 2400
		ValidRelationships: Enemy
		Versus:
			None: 130
			Light: 45
			Heavy: 12
SF_CinderMaw:
	Inherits: SF_Cinder
	ReloadDelay: 65
	Range: 4c0
	Warhead@1Dam:
		Damage: 13000
		ValidRelationships: Enemy
		Versus:
			None: 35
			Light: 100
			Heavy: 110
'''
    weapons = weapons.replace('Warhead@1Dam:\n', 'Warhead@1Dam: SpreadDamage\n')
    for name, damage, reload in [('Skyward', 4200, 55), ('Skyguard', 3800, 45), ('Skyhook', 4800, 65)]:
        weapons += f'SF_{name}:\n\tInherits: RedEye\n\tRange: 7c512\n\tReloadDelay: {reload}\n\tWarhead@1Dam: SpreadDamage\n\t\tDamage: {damage}\n\t\tValidRelationships: Enemy\n'
    weapon_by_actor = dict(a_watchfire='Watchfire', a_judgment='Judgment', a_skyward='Skyward', h_autocannon='Autocannon', h_missilenest='Skyguard', d_spinenest='Spines', d_cindermaw='CinderMaw', d_skyhook='Skyhook')
    aura_by_actor = {'a_dawnwall': ('Light', '0c640', 500000, 0), 'a_sanctuary': ('Sanctuary', '4c0', 0, 50),
                     'd_mourningwall': ('Flesh', '3c0', 0, 0), 'h_razorwire': ('Wire', '0c700', 100, 0),
                     'd_thornfield': ('Thorns', '0c700', 150, 0)}
    for index, entry in enumerate(catalogue):
        actor = entry['id']; key = actor.replace('_', '-'); wall = entry['wall']
        parent = {'a': 'angels', 'h': 'humans', 'd': 'demons'}[actor[0]]
        rules += f'{actor.upper()}:\n\tInherits: ^SF_' + ('WALL' if wall else 'EMPLACEMENT') + '\n'
        if entry['power']:
            rules += '\tInherits@SF_POWER: ^DisableOnLowPower' + ('' if wall else 'OrPowerDown') + '\n'
        if actor in weapon_by_actor or entry['role'] == 'garrison':
            rules += '\tInherits@AUTOTARGET: ^AutoTarget' + ('Air' if entry['role'] == 'anti-air' else 'Ground') + '\n'
        rules += f'\tRenderSprites:\n\t\tImage: {actor}\n\tBuildable:\n\t\tQueue: Defense\n\t\tBuildPaletteOrder: {10 + index*5}\n\t\tPrerequisites: {entry["prerequisite"]}, ~sf.{parent}, ~techlevel.' + ('infonly' if wall else 'low' if entry['role'] in ('garrison', 'anti-infantry', 'anti-ground', 'sanctuary') else 'medium') + f'\n\t\tDescription: sf-{key}-description\n\tTooltip:\n\t\tName: sf-{key}-name\n\tValued:\n\t\tCost: {entry["cost"]}\n\tHealth:\n\t\tHP: {entry["hp"]}\n\tPower:\n\t\tAmount: {-entry["power"]}\n'
        if wall:
            rules += f'\tLineBuild:\n\t\tNodeTypes: {actor}\n\tLineBuildNode:\n\t\tTypes: {actor}\n'
            if entry['role'] in ('wire', 'thorns') or actor == 'a_dawnwall':
                rules += '\tBuilding:\n\t\tFootprint: =\n'
            if actor == 'a_dawnwall':
                rules += '\t-Crushable:\n\tWithSpriteBody:\n\t\tRequiresCondition: !disabled\n\tWithSpriteBody@OFF:\n\t\tName: offline\n\t\tSequence: offline\n\t\tRequiresCondition: disabled\n'
            elif actor == 'h_blastwall':
                rules += '\tArmor:\n\t\tType: Concrete\n\tCrushable:\n\t\tCrushClasses: heavywall\n\tBlocksProjectiles:\n'
            elif actor == 'd_mourningwall':
                rules += '\tCrushable:\n\t\tCrushClasses: heavywall\n\tChangesHealth:\n\t\tStep: 120\n\t\tDelay: 25\n\t\tStartIfBelow: 100\n\t\tDamageCooldown: 100\n\tAmbientSound:\n\t\tSoundFiles: sevenfall|audio/sf-mourning.wav\n\t\tDelay: 10, 80\n\t\tInterval: 120, 200\n\t\tRequiresCondition: !disabled\n'
            if actor in ('a_dawnwall', 'd_mourningwall'):
                rules += '\tTargetable:\n\t\tTargetTypes: GroundActor, Structure, Wall, Defense\n'
        if actor in aura_by_actor:
            kind, radius, damage, heal = aura_by_actor[actor]
            rules += f'\tSFDefenseSource:\n\t\tKind: {kind}\n\t\tRange: {radius}\n\t\tDamage: {damage}\n\t\tHeal: {heal}\n'
            if entry['power']:
                rules += '\t\tRequiresCondition: !disabled' + ('' if wall else ' && !build-incomplete') + '\n'
            rules += f'\tWithRangeCircle@SF_AURA:\n\t\tRange: {radius}\n\t\tType: {actor}\n\t\tColor: ' + ('C249D580' if actor[0] == 'd' else '86E7FF80') + '\n'
            if not wall and actor not in weapon_by_actor:
                rules += '\t-RenderRangeCircle:\n'
        if entry['power']:
            rules += '\tWithColoredOverlay@SF_OFFLINE:\n\t\tColor: 00000090\n\t\tRequiresCondition: disabled\n'
        if actor in weapon_by_actor:
            pause = 'disabled || build-incomplete' if entry['power'] else 'build-incomplete'
            rules += f'\tArmament:\n\t\tWeapon: SF_{weapon_by_actor[actor]}\n\t\tLocalOffset: 0,0,700\n\tAttackOmni:\n\t\tPauseOnCondition: {pause}\n\tWithAttackAnimation:\n\t\tSequence: shoot\n\t\tDelayRelativeTo: Attack\n'
        if entry['role'] == 'garrison':
            rules += '''	Inherits@PIPS: ^CargoPips
	Cargo:
		Types: Infantry
		MaxWeight: 3
		EjectOnDeath: True
	AttackGarrisoned:
		PauseOnCondition: build-incomplete
		Armaments: garrisoned
		PortOffsets: 512,0,128, 0,-512,128, -512,0,128, 0,512,128
		PortYaws: 0, 256, 512, 768
		PortCones: 128, 128, 128, 128
	RenderRangeCircle:
		FallbackRange: 6c0
'''
        rules += '\n'
        filename = f'sevenfall|art/defenses/{actor}.png'
        sequences += f'{actor}:\n\tDefaults:\n\t\tFilename: {filename}\n\t\tOffset: 0,' + ('-8' if wall else '-12') + '\n\tidle:\n'
        if actor in ('d_mourningwall', 'd_thornfield', 'a_sanctuary'):
            sequences += '\t\tFrames: 0,4,5\n\t\tLength: 3\n\t\tTick: 220\n'
        for state, start in [('damaged-idle',1), ('critical-idle',2), ('make',0), ('damaged-shoot',1), ('critical-shoot',2), ('offline',3)]:
            sequences += f'\t{state}:\n\t\tStart: {start}\n'
        sequences += '\tshoot:\n\t\tStart: 3\n\t\tLength: 3\n\t\tTick: 80\n'
        sequences += f'\ticon:\n\t\tFilename: sevenfall|art/defenses/{actor}-icon.png\n\t\tOffset: 0,0\n\n'
        messages += [f'sf-{key}-name = {entry["name"]}', f'sf-{key}-description = {entry["description"]}']
    (MOD / 'rules/45-defenses.yaml').write_text(rules.rstrip() + '\n', encoding='utf-8')
    (MOD / 'sequences/defenses.yaml').write_text(sequences.rstrip() + '\n', encoding='utf-8')
    (MOD / 'weapons/defenses.yaml').write_text(weapons.rstrip() + '\n', encoding='utf-8')
    fluent = MOD / 'fluent/sevenfall.ftl'
    existing = fluent.read_text(encoding='utf-8').split('# Sevenfall defense roster')[0].rstrip()
    fluent.write_text(existing + '\n\n# Sevenfall defense roster\n' + '\n'.join(messages) + '\n', encoding='utf-8')
    factions = MOD / 'rules/10-factions.yaml'
    text = factions.read_text(encoding='utf-8')
    text = text.replace('^BaseWorld:\n\tSFDefenseManager:\n', '^BaseWorld:\n')
    if '\tSFDefenseManager:' not in text:
        text, count = re.subn(r'(?m)^World:\n', 'World:\n\tSFDefenseManager:\n', text, count=1)
        if not count:
            text += '\nWorld:\n\tSFDefenseManager:\n'
    if 'SFDreadBar:' not in text:
        text += '''
^Infantry:
	SFDreadBar:
	ExternalCondition@SF_DREAD:
		Condition: sf-dread
		TotalCap: 1
	ExternalCondition@SF_WIRE:
		Condition: sf-wire
		TotalCap: 1
	ExternalCondition@SF_THORNS:
		Condition: sf-thorns
		TotalCap: 1
	SpeedMultiplier@SF_WIRE:
		Modifier: 65
		RequiresCondition: sf-wire
	SpeedMultiplier@SF_THORNS:
		Modifier: 50
		RequiresCondition: sf-thorns
	WithColoredOverlay@SF_DREAD:
		Color: B146D268
		RequiresCondition: sf-dread
'''
    factions.write_text(text, encoding='utf-8')
    ai = MOD / 'rules/40-ai.yaml'
    text = ai.read_text(encoding='utf-8')
    if '\t\tDefenseTypes:' not in text:
        defenses = list(weapon_by_actor)
        text = text.replace('\t\tBuildingLimits:\n', '\t\tDefenseTypes: ' + ', '.join(defenses) + '\n\t\tBuildingLimits:\n' + ''.join(f'\t\t\t{a}: 2\n' for a in defenses), 1)
        text = text.replace('\t\tBuildingFractions:\n', '\t\tBuildingFractions:\n' + ''.join(f'\t\t\t{a}: 4\n' for a in defenses), 1)
    ai.write_text(text, encoding='utf-8')
    print('Generated 15 defenses, eight weapons and 30 localized descriptions/names.')


if __name__ == '__main__':
    main()

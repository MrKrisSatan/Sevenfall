const fs = require('node:fs/promises');
const path = require('node:path');
const sharp = require('sharp');
const root = path.resolve(__dirname, '..');
const themes = {
  neutral: {base:'#181b20', edge:'#78828d', accent:'#c2c8cf'},
  angelic: {base:'#292a29', edge:'#9e8961', accent:'#eedaa2'},
  human: {base:'#192830', edge:'#527f8c', accent:'#8bd8df'},
  infernal: {base:'#2a1a20', edge:'#974d47', accent:'#f49768'},
  machine: {base:'#101f28', edge:'#467ca8', accent:'#70f6ee'},
  fallen: {base:'#261d30', edge:'#8c708f', accent:'#d6b3d3'}
};
const svg = (w,h,body) => `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}">${body}</svg>`;
function panel(x,y,w,h,t,fill=t.base) {
  return `<rect x="${x}" y="${y}" width="${w}" height="${h}" fill="${fill}"/><rect x="${x+1}" y="${y+1}" width="${w-2}" height="${h-2}" fill="none" stroke="${t.edge}"/><path d="M${x+3} ${y+h-3} V${y+3} H${x+w-3}" fill="none" stroke="${t.accent}" opacity=".3"/>`;
}
function mark(theme,x,y,r) {
  let d;
  if(theme==='angelic') d='M0 -26 L7 -7 L30 -18 L20 3 L8 13 L0 27 L-8 13 L-20 3 L-30 -18 L-7 -7 Z M-24 -10 L-9 2 M24 -10 L9 2';
  else if(theme==='human') d='M-23 -24 H23 V5 L0 27 L-23 5 Z M-12 9 V-10 H-3 V-18 H5 V-10 H13 V9 M-16 15 H16';
  else if(theme==='infernal') d='M-27 -27 L-9 -11 L0 -21 L9 -11 L27 -27 L21 3 L0 28 L-21 3 Z M0 -8 L9 5 L0 18 L-9 5 Z';
  else if(theme==='machine') d='M-18 -18 H18 V18 H-18 Z M-8 -8 H8 V8 H-8 Z M0 -30 V-18 M0 18 V30 M-30 0 H-18 M18 0 H30 M-26 -26 L-18 -18 M18 18 L26 26';
  else if(theme==='fallen') d='M-24 -21 L-10 -7 L-30 5 L-12 3 L-20 21 L0 11 L20 21 L12 3 L30 5 L10 -7 L24 -21 M-12 -24 Q0 -31 12 -24 M-8 -20 L0 11 L8 -20';
  else d='M0 -28 L22 -17 L27 7 L12 25 L-12 25 L-27 7 L-22 -17 Z M0 -28 V28 M-27 7 L22 -17 M27 7 L-22 -17';
  return `<g transform="translate(${x} ${y}) scale(${r/30})" fill="none" stroke="${themes[theme].accent}" stroke-width="1.8" stroke-linejoin="round"><path d="${d}"/></g>`;
}
async function exportSvg(name,w,h,body,scales=[1,2,3]) {
  const source=svg(w,h,body);
  await fs.writeFile(path.join(root,'art/ui',name+'.svg'),source);
  for(const scale of scales) await sharp(Buffer.from(source)).resize(w*scale,h*scale).png()
    .toFile(path.join(root,'mods/sevenfall/art/ui',name+(scale===1?'':`-${scale}x`)+'.png'));
}
const image = name => `\tImage: sevenfall|art/ui/${name}.png\n\tImage2x: sevenfall|art/ui/${name}-2x.png\n\tImage3x: sevenfall|art/ui/${name}-3x.png\n`;
(async()=>{
  await fs.mkdir(path.join(root,'art/ui'),{recursive:true});
  await fs.mkdir(path.join(root,'mods/sevenfall/art/ui'),{recursive:true});
  let yaml='# Generated by scripts/build_ui.cjs; original Sevenfall interface.\n';
  for(const [name,t] of Object.entries(themes)) {
    let body=panel(0,0,238,262,t)+panel(0,264,238,28,t)+panel(0,294,190,47,t);
    // Foreground strips must leave production icons and support powers visible.
    body+=panel(0,343,238,47,t,'none')+panel(0,392,238,8,t)+panel(240,0,222,222,t);
    body+=mark(name,351,111,48);
    body+=`<path d="M251 111 H285 M417 111 H451 M351 11 V45 M351 177 V211" stroke="${t.edge}" fill="none"/>`;
    body+=panel(240,224,64,48,t,'none')+panel(0,404,434,44,t);
    for(let i=0;i<8;i++) {
      const stateTheme=i>=4?{...t,edge:t.accent}:t;
      body+=panel(464,i*32,30,30,stateTheme,[2,3,6,7].includes(i)?'#101215':i===1||i===5?t.edge:t.base);
    }
    await exportSvg('hud-'+name,512,512,body);
    yaml+=`sidebar-${name}:\n${image('hud-'+name)}\tRegions:\n\t\tradar: 240, 0, 222, 222\n\t\tbackground-top: 0, 0, 238, 262\n\t\tbackground-moneybin: 0, 264, 238, 28\n\t\tbackground-iconbg: 0, 294, 190, 47\n\t\tbackground-iconrow: 0, 343, 238, 47\n\t\tbackground-bottom: 0, 392, 238, 8\n\t\tbackground-supportoverlay: 240, 224, 64, 48\n`;
    yaml+=`commandbar-${name}:\n${image('hud-'+name)}\tRegions:\n\t\tbackground: 0, 404, 434, 44\n`;
    const states=['','-hover','-pressed','-disabled','-highlighted','-highlighted-hover','-highlighted-pressed','-highlighted-disabled'];
    for(const kind of ['sidebar-button','command-button']) states.forEach((state,i)=>{
      yaml+=`${kind}-${name}${state}:\n${image('hud-'+name)}\tPanelRegion: 464, ${i*32}, 3, 3, 24, 24, 3, 3\n`;
    });
  }
  // Generic menus are always neutral, including lobby and settings dialogs.
  const t=themes.neutral;
  let dialog=panel(1,1,480,480,t);
  for(const [x,y,w,h] of [[492,1,9,190],[483,1,9,190],[1,492,189,9],[1,483,189,9],
    [192,483,9,9],[201,483,9,9],[192,492,9,9],[201,492,9,9],[512,387,64,64],[580,388,62,62],[650,389,116,116]])
    dialog+=panel(x,y,w,h,t);
  for(const x of [513,641,769,897]) for(const y of [1,129,257,385])
    if(y!==385 || x>=769) dialog+=panel(x,y,126,126,t,y===257?'#12151a':y===129?'#303740':t.base);
  await exportSvg('neutral-dialog',1024,512,dialog);
  yaml+=`^Dialog:\n${image('neutral-dialog')}`;
  yaml+='sidebar:\n\tInherits: sidebar-neutral\nsidebar-button:\n\tInherits: sidebar-button-neutral\ncommand-button:\n\tInherits: command-button-neutral\n';
  yaml+=`commandbar:\n${image('hud-neutral')}\tRegions:\n\t\tbackground: 0, 404, 434, 44\n`;
  yaml+=`sidebar-observer:\n${image('hud-neutral')}\tRegions:\n\t\tbackground: 0, 0, 238, 262\n\t\treplay-bottom: 0, 404, 238, 40\n\t\tobserver-bottom: 0, 392, 238, 8\n`;
  for(const [i,s] of ['','-hover','-pressed','-disabled','-highlighted','-highlighted-hover','-highlighted-pressed','-highlighted-disabled'].entries())
    yaml+=`sidebar-button-observer${s}:\n${image('hud-neutral')}\tPanelRegion: 464, ${i*32}, 3, 3, 24, 24, 3, 3\n`;
  const logo=mark('neutral',128,88,57)+`<text x="128" y="183" text-anchor="middle" font-family="sans-serif" font-size="29" letter-spacing="3" fill="#e1e4e8">SEVENFALL</text><text x="128" y="207" text-anchor="middle" font-family="sans-serif" font-size="10" letter-spacing="2" fill="#aeb7c1">THE WAR FOR CREATION</text>`;
  await exportSvg('neutral-brand',512,256,logo+panel(258,0,254,256,t));
  yaml+=`^LoadScreen:\n${image('neutral-brand')}`;
  await fs.writeFile(path.join(root,'mods/sevenfall/chrome-ui.yaml'),yaml);
  let preview='';
  for(const [i,name] of Object.keys(themes).entries()) {
    const x=i*280; preview+=panel(x,0,260,390,themes[name])+mark(name,x+130,100,55);
    preview+=`<text x="${x+130}" y="190" text-anchor="middle" fill="${themes[name].accent}" font-family="sans-serif" font-size="20">${name.toUpperCase()}</text>`;
    preview+=panel(x+20,220,220,36,themes[name])+panel(x+20,270,220,80,themes[name]);
  }
  const previewWidth=Object.keys(themes).length*280;
  await fs.writeFile(path.join(root,'art/ui/theme-preview.svg'),svg(previewWidth,390,preview));
  await sharp(Buffer.from(svg(previewWidth,390,preview))).png().toFile(path.join(root,'art/ui/theme-preview.png'));
})();
